/**
 * Look up a word. Returns a short definition string or null if not found.
 * @param {string} word
 * @returns {string|null}
 */
export function lookupWord(word) {
  if (!word) return null;
  const key = word.toLowerCase().replace(/[^a-z]/g, '');
  return DICT[key] || null;
}

